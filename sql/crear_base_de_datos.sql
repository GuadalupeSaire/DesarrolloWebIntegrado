CREATE EXTENSION IF NOT EXISTS pgcrypto;   -- para generar el hash BCrypt del admin inicial

-- ---------------------------------------------------------------------
-- SEGURIDAD Y USUARIOS
-- ---------------------------------------------------------------------
CREATE TABLE roles (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(60)  NOT NULL UNIQUE,
    descripcion  VARCHAR(250)
);

CREATE TABLE usuarios (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres        VARCHAR(80)  NOT NULL,
    apellidos      VARCHAR(80)  NOT NULL,
    correo         VARCHAR(150) NOT NULL UNIQUE,
    password_hash  VARCHAR(255) NOT NULL,
    estado         BOOLEAN      NOT NULL DEFAULT TRUE,
    creado_en      TIMESTAMP(6) NOT NULL DEFAULT NOW()
);

CREATE TABLE usuario_roles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT NOT NULL REFERENCES usuarios(id),
    rol_id      BIGINT NOT NULL REFERENCES roles(id),
    asignado_en TIMESTAMP(6) NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_usuario_rol UNIQUE (usuario_id, rol_id)
);

-- ---------------------------------------------------------------------
-- EMPRESAS CLIENTE
-- ---------------------------------------------------------------------
CREATE TABLE empresas (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    razon_social VARCHAR(150) NOT NULL,
    ruc          VARCHAR(11)  NOT NULL UNIQUE,
    direccion    VARCHAR(200),
    telefono     VARCHAR(9),
    correo       VARCHAR(100),
    estado       BOOLEAN      NOT NULL DEFAULT TRUE,
    creado_en    TIMESTAMP(6) NOT NULL DEFAULT NOW()
);

CREATE TABLE usuario_empresas (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id       BIGINT  NOT NULL REFERENCES usuarios(id),
    empresa_id       BIGINT  NOT NULL REFERENCES empresas(id),
    fecha_asignacion DATE    NOT NULL DEFAULT CURRENT_DATE,
    estado           BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_usuario_empresa UNIQUE (usuario_id, empresa_id)
);

CREATE TABLE contactos (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT       NOT NULL REFERENCES empresas(id),
    nombre     VARCHAR(120) NOT NULL,
    cargo      VARCHAR(100),
    correo     VARCHAR(150),
    telefono   VARCHAR(20),
    principal  BOOLEAN      NOT NULL DEFAULT FALSE
);

-- ---------------------------------------------------------------------
-- RECLUTAMIENTO (ATS)
-- ---------------------------------------------------------------------
CREATE TABLE candidatos (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres          VARCHAR(100) NOT NULL,
    apellidos        VARCHAR(100) NOT NULL,
    tipo_documento   VARCHAR(10),
    documento_numero VARCHAR(20),
    correo           VARCHAR(150),
    telefono         VARCHAR(20),
    archivo_cv       VARCHAR(500),
    texto_cv         TEXT,
    creado_en        TIMESTAMP(6) NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_candidato_documento UNIQUE (documento_numero)   -- RF006: sin duplicados por DNI
);

CREATE TABLE vacantes (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id         BIGINT       NOT NULL REFERENCES empresas(id),
    creado_por         BIGINT       REFERENCES usuarios(id),
    titulo             VARCHAR(150) NOT NULL,
    descripcion        TEXT,
    requisitos         TEXT,
    nivel_educativo    VARCHAR(100),
    competencias       TEXT,
    salario            NUMERIC(12,2),
    fecha_publicacion  DATE,
    fecha_cierre       DATE,
    sla_dias           INTEGER,
    estado             VARCHAR(20) NOT NULL DEFAULT 'BORRADOR',
    CONSTRAINT vacantes_estado_check
        CHECK (estado IN ('BORRADOR','PUBLICADA','CERRADA','CANCELADA'))
);

CREATE TABLE postulaciones (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vacante_id         BIGINT       NOT NULL REFERENCES vacantes(id),
    candidato_id       BIGINT       NOT NULL REFERENCES candidatos(id),
    puntaje_cv         NUMERIC(5,2),
    fecha_postulacion  TIMESTAMP(6) NOT NULL DEFAULT NOW(),
    estado             VARCHAR(25)  NOT NULL DEFAULT 'RECIBIDA',
    observaciones      TEXT,
    CONSTRAINT uk_postulacion UNIQUE (vacante_id, candidato_id),
    CONSTRAINT postulaciones_estado_check
        CHECK (estado IN ('RECIBIDA','EN_REVISION','PRESELECCIONADA','ENTREVISTA','APROBADA','RECHAZADA','CONTRATADA'))
);

CREATE TABLE etapas_postulacion (       -- historial de cambios de estado (RF009)
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    postulacion_id BIGINT       NOT NULL REFERENCES postulaciones(id),
    usuario_id     BIGINT       REFERENCES usuarios(id),
    etapa          VARCHAR(60)  NOT NULL,
    fecha_inicio   TIMESTAMP(6) NOT NULL DEFAULT NOW(),
    fecha_fin      TIMESTAMP(6),
    comentario     TEXT
);

-- ---------------------------------------------------------------------
-- PLANILLAS (cálculo interno)
-- ---------------------------------------------------------------------
CREATE TABLE trabajadores (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id          BIGINT        NOT NULL REFERENCES empresas(id),
    nombres             VARCHAR(100)  NOT NULL,
    apellidos           VARCHAR(100)  NOT NULL,
    tipo_documento      VARCHAR(10),
    documento_numero    VARCHAR(20)   NOT NULL,
    correo              VARCHAR(150),
    telefono            VARCHAR(20),
    cargo               VARCHAR(120),
    fecha_ingreso       DATE,
    fecha_cese          DATE,
    sueldo_base         NUMERIC(12,2) NOT NULL DEFAULT 0,
    regimen_pensionario VARCHAR(10)   DEFAULT 'ONP',
    tasa_pension        NUMERIC(6,4)  DEFAULT 0.1300,
    activo              BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_trabajador_empresa_doc UNIQUE (empresa_id, documento_numero)
);

CREATE TABLE planillas (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id       BIGINT       NOT NULL REFERENCES empresas(id),
    periodo_anio     INTEGER      NOT NULL,
    periodo_mes      INTEGER      NOT NULL,
    procesada_por    BIGINT       REFERENCES usuarios(id),
    fecha_proceso    TIMESTAMP(6),
    estado           VARCHAR(20)  NOT NULL DEFAULT 'BORRADOR',
    total_bruto      NUMERIC(14,2) DEFAULT 0,
    total_descuentos NUMERIC(14,2) DEFAULT 0,
    total_neto       NUMERIC(14,2) DEFAULT 0,
    CONSTRAINT uk_planilla_periodo UNIQUE (empresa_id, periodo_anio, periodo_mes),
    CONSTRAINT planillas_estado_check CHECK (estado IN ('BORRADOR','CALCULADA','CERRADA')),
    CONSTRAINT planillas_mes_check CHECK (periodo_mes BETWEEN 1 AND 12)
);

CREATE TABLE detalles_planilla (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    planilla_id         BIGINT NOT NULL REFERENCES planillas(id),
    trabajador_id       BIGINT NOT NULL REFERENCES trabajadores(id),
    dias_laborados      INTEGER,
    faltas              INTEGER DEFAULT 0,
    horas_extra         NUMERIC(8,2)  DEFAULT 0,
    sueldo_base         NUMERIC(12,2) DEFAULT 0,
    bonificaciones      NUMERIC(12,2) DEFAULT 0,
    descuentos          NUMERIC(12,2) DEFAULT 0,
    aporte_pension      NUMERIC(12,2) DEFAULT 0,
    retencion_quinta    NUMERIC(12,2) DEFAULT 0,
    essalud_empleador   NUMERIC(12,2) DEFAULT 0,
    subsidios           NUMERIC(12,2) DEFAULT 0,
    horas_extra_importe NUMERIC(12,2) DEFAULT 0,
    total_bruto         NUMERIC(12,2) DEFAULT 0,
    total_neto          NUMERIC(12,2) DEFAULT 0,
    CONSTRAINT uk_detalle_planilla_trab UNIQUE (planilla_id, trabajador_id)
);

-- ---------------------------------------------------------------------
-- AUDITORÍA (RNF008)
-- ---------------------------------------------------------------------
CREATE TABLE auditorias (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     BIGINT       REFERENCES usuarios(id),
    empresa_id     BIGINT       REFERENCES empresas(id),
    entidad        VARCHAR(80)  NOT NULL,
    entidad_id     BIGINT,
    accion         VARCHAR(40)  NOT NULL,
    fecha_evento   TIMESTAMP(6) NOT NULL DEFAULT NOW(),
    valor_anterior TEXT,
    valor_nuevo    TEXT,
    ip_origen      VARCHAR(50)
);

-- ---------------------------------------------------------------------
-- ÍNDICES de apoyo (búsquedas y filtros por empresa - RNF001 / RNF004)
-- ---------------------------------------------------------------------
CREATE INDEX idx_vacantes_empresa        ON vacantes(empresa_id);
CREATE INDEX idx_postulaciones_vacante   ON postulaciones(vacante_id);
CREATE INDEX idx_postulaciones_candidato ON postulaciones(candidato_id);
CREATE INDEX idx_etapas_postulacion      ON etapas_postulacion(postulacion_id);
CREATE INDEX idx_trabajadores_empresa    ON trabajadores(empresa_id);
CREATE INDEX idx_planillas_empresa       ON planillas(empresa_id);
CREATE INDEX idx_detalles_planilla       ON detalles_planilla(planilla_id);
CREATE INDEX idx_contactos_empresa       ON contactos(empresa_id);
CREATE INDEX idx_usuario_empresas_emp    ON usuario_empresas(empresa_id);
CREATE INDEX idx_auditorias_fecha        ON auditorias(fecha_evento);

